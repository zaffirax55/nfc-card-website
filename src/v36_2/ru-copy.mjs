export function russianCopyReadiness(route){
 const page=russianPageCopy(route);
 if(!page)return Object.freeze({knownRoute:false,ready:false,missingKeys:Object.freeze([])});
 const missingKeys=RU_PENDING_COPY.filter(row=>row.routes.includes('/ru'+route)).map(row=>row.source_key);
 for(const key of ['title','description','h1','intro']){
  if(typeof page[key]!=='string'||!page[key].trim())missingKeys.push(key);
 }
 return Object.freeze({knownRoute:true,ready:missingKeys.length===0,missingKeys:Object.freeze(missingKeys)});
}
/** Use before integrating a page renderer; incomplete bodies must not masquerade as complete. */
export function requireRussianPageCopy(route){
 const state=russianCopyReadiness(route);if(!state.knownRoute)throw new RangeError('Unsupported Russian route: '+route);
 if(!state.ready)throw new MissingRussianCopyError(state.missingKeys.join(', '));return russianPageCopy(route);
}
